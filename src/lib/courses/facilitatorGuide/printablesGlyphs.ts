/**
 * WHICH CHARACTERS THE PRINTABLES' PDF CAN DRAW, and how it draws the rest.
 *
 * The PDF embeds the house's fonts and no others (`src/lib/courses/
 * certificates/fonts/`): Space Grotesk for text (its two weights cover the
 * same characters) and Space Mono for the templates. A character is drawn in
 * its own face when that face has it, in the other face when only that one
 * does, and as an empty box (the sign every reader knows for a character a
 * font cannot draw) when neither does, never as nothing. The loader names
 * every such character when the printables are loaded (`undrawableIn`), so a
 * box is seen before anybody prints one.
 *
 * Neither real course's printables carries a character outside these faces;
 * the box is for what a later paste may bring (a tick mark, scissors, an
 * emoji).
 *
 * The tables below are the fonts' own character maps, as ranges of code
 * points. `tests/course-facilitator-guide-printables.test.mjs` reads the font
 * files and fails when they and these tables disagree, so a font changed
 * without its table is caught.
 *
 * Pure.
 */

