function inRanges(ranges: Ranges, cp: number): boolean {
  let lo = 0;
  let hi = ranges.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [start, end] = ranges[mid];
    if (cp < start) hi = mid - 1;
    else if (cp > end) lo = mid + 1;
    else return true;
  }
  return false;
}

/** Does `face` have a glyph for the code point? */
export function faceHas(face: GlyphFace, cp: number): boolean {
  return inRanges(face === "text" ? TEXT_FACE_CHARACTERS : MONO_FACE_CHARACTERS, cp);
}

/**
 * How one character is drawn in `face`: in that face, in the other one, or as
 * a box. A space neither face has (a narrow no-break space, say) is drawn as
 * an ordinary space, which is what it looks like.
 */
export function drawnAs(face: GlyphFace, ch: string): { kind: "face"; face: GlyphFace; ch: string } | { kind: "box" } {
  const cp = ch.codePointAt(0) ?? 0;
  if (faceHas(face, cp)) return { kind: "face", face, ch };
  const other: GlyphFace = face === "text" ? "mono" : "text";
  if (faceHas(other, cp)) return { kind: "face", face: other, ch };
  if (/^\p{Zs}$/u.test(ch)) return { kind: "face", face, ch: " " };
  return { kind: "box" };
}

/**
 * Text as it is drawn: canonical (NFC, so a letter and its accent written
 * apart are the one letter the fonts have), with the characters that draw as
 * nothing anywhere left out (control characters other than a tab and a line
 * break, zero-width and joining marks, a soft hyphen, a byte-order mark).
 */
export function drawableText(text: string): string {
  return text.normalize("NFC").replace(/[^\P{Cc}\t\n]|\p{Default_Ignorable_Code_Point}/gu, "");
}

/**
 * The characters in some text that neither face can draw, once each, in the
 * order they first appear: what the PDF draws as a box.
 */
export function undrawableIn(text: string): string[] {
  const out: string[] = [];
  for (const ch of drawableText(text)) {
    if (ch === "\n" || ch === "\t") continue;
    if (drawnAs("text", ch).kind === "box" && !out.includes(ch)) out.push(ch);
  }
  return out;
}

/** "✂ (U+2702)": a character and its code, for a sentence that names it. */
export function characterName(ch: string): string {
  return `${ch} (U+${(ch.codePointAt(0) ?? 0).toString(16).toUpperCase().padStart(4, "0")})`;
}
